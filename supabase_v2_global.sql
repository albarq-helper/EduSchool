-- Run AFTER supabase_setup.sql (safe to run more than once).
-- Adds schools/universities, subjects, levels (KG → postgraduate),
-- study sets made by teachers (terms + multiple-choice / true-false
-- questions), sharing to a public library, assigning sets to classes,
-- a media bucket for pictures/audio, and a site admin role.
-- =====================================================================

-- ---------- Lookup tables ----------
create table if not exists public.institutions (
  id          uuid primary key default gen_random_uuid(),
  name        text not null check (length(trim(name)) between 2 and 120),
  kind        text not null default 'school' check (kind in ('school','university','college','institute','other')),
  country     text not null default '' check (length(country) <= 60),
  city        text not null default '' check (length(city) <= 60),
  created_by  uuid references public.profiles(id) on delete set null,
  created_at  timestamptz not null default now()
);
create unique index if not exists institutions_name_uq on public.institutions (lower(trim(name)), lower(trim(country)));

create table if not exists public.subjects (
  id    int primary key generated by default as identity,
  name  text not null unique check (length(trim(name)) between 2 and 60),
