-- ---------- Helper functions ----------
create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from profiles where id = auth.uid() and is_admin);
$$;

create or replace function public.can_view_set(p_set uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from study_sets s where s.id = p_set and
           (s.visibility = 'public' or s.owner_id = auth.uid()
            or exists (select 1 from profiles where id = auth.uid() and is_admin)
            or exists (select 1 from class_sets cs join classes c on c.id = cs.class_id
                       where cs.set_id = s.id and (c.teacher_id = auth.uid()
                         or exists (select 1 from class_members m where m.class_id = c.id and m.student_id = auth.uid())))));
$$;

create or replace function public.owns_set(p_set uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from study_sets s where s.id = p_set and
           (s.owner_id = auth.uid() or exists (select 1 from profiles where id = auth.uid() and is_admin)));
$$;

create or replace function public.owns_class(p_class uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from classes where id = p_class and teacher_id = auth.uid());
$$;

-- Find or create an institution by name (used at sign-up and from the website).
create or replace function public.institution_id_for(p_name text, p_kind text, p_country text, p_city text, p_user uuid)
returns uuid language plpgsql security definer set search_path = public as $$
declare v uuid; n text := trim(coalesce(p_name,'')); c text := trim(coalesce(p_country,''));
begin
  if length(n) < 2 then return null; end if;
  select id into v from institutions where lower(trim(name)) = lower(n) and lower(trim(country)) = lower(c);
  if v is null then
    insert into institutions (name, kind, country, city, created_by)
    values (left(n,120),
            case when p_kind in ('school','university','college','institute','other') then p_kind else 'school' end,
            left(c,60), left(trim(coalesce(p_city,'')),60), p_user)
    on conflict do nothing returning id into v;
    if v is null then select id into v from institutions where lower(trim(name)) = lower(n) and lower(trim(country)) = lower(c); end if;
  end if;
  return v;
end $$;

create or replace function public.add_institution(p_name text, p_kind text, p_country text, p_city text)
returns uuid language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null then raise exception 'Not signed in'; end if;
  return institution_id_for(p_name, p_kind, p_country, p_city, auth.uid());
end $$;

-- Profile row on sign-up, now with school/university and level.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
declare m jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb); inst uuid; lvl text;
begin
  insert into profiles (id, full_name, role)
  values (new.id, coalesce(m->>'full_name', ''), case when m->>'role' = 'teacher' then 'teacher' else 'student' end)
  on conflict (id) do nothing;
  if (m->>'institution_id') ~ '^[0-9a-f-]{36}$' then
    select id into inst from institutions where id = (m->>'institution_id')::uuid;
  end if;
  if inst is null and coalesce(m->>'institution_name','') <> '' then
    inst := institution_id_for(m->>'institution_name', m->>'institution_kind', m->>'institution_country', m->>'institution_city', new.id);
  end if;
  select code into lvl from levels where code = m->>'level_code';
  update profiles set institution_id = inst, level_code = lvl where id = new.id;
  return new;
end $$;

-- Nobody can change their own role or admin flag from the website.
create or replace function public.protect_role()
returns trigger language plpgsql as $$
begin
  if (new.role is distinct from old.role or new.is_admin is distinct from old.is_admin)
     and current_user not in ('postgres','service_role','supabase_admin') then
    raise exception 'Role cannot be changed from the website';
  end if;
  return new;
end $$;

-- Set rows: stamp the author's name, keep the owner, keep timestamps.
create or replace function public.study_sets_stamp()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    if new.owner_id is not null then
      select full_name into new.author_name from profiles where id = new.owner_id;
      new.author_name := coalesce(new.author_name, '');
    end if;
    new.term_count := 0; new.question_count := 0;
  else
    if new.owner_id is distinct from old.owner_id and not exists (select 1 from profiles where id = auth.uid() and is_admin)
       and current_user not in ('postgres','service_role','supabase_admin') then
      raise exception 'Owner cannot be changed';
    end if;
    new.updated_at := now();
  end if;
  return new;
end $$;
drop trigger if exists study_sets_stamp on public.study_sets;
create trigger study_sets_stamp before insert or update on public.study_sets
  for each row execute function public.study_sets_stamp();

-- Keep term/question counts up to date.
create or replace function public.set_items_count()
returns trigger language plpgsql security definer set search_path = public as $$
declare sid uuid := coalesce(new.set_id, old.set_id);
begin
  update study_sets set
    term_count     = (select count(*) from set_items where set_id = sid and kind = 'term'),
    question_count = (select count(*) from set_items where set_id = sid and kind <> 'term'),
    cover_url      = coalesce((select coalesce(nullif(image_url,''), anim_url) from set_items
                               where set_id = sid and (image_url <> '' or anim_url <> '') order by position limit 1), '')
  where id = sid;
  if tg_op = 'UPDATE' and new.set_id <> old.set_id then
    update study_sets set
      term_count     = (select count(*) from set_items where set_id = old.set_id and kind = 'term'),
      question_count = (select count(*) from set_items where set_id = old.set_id and kind <> 'term')
    where id = old.set_id;
  end if;
  return null;
end $$;
drop trigger if exists set_items_count on public.set_items;
create trigger set_items_count after insert or update or delete on public.set_items
  for each row execute function public.set_items_count();

-- A teacher copies any set they can see into their own (private) sets.
create or replace function public.copy_set(p_set uuid)
returns uuid language plpgsql security definer set search_path = public as $$
declare s study_sets%rowtype; nid uuid; inst uuid;
begin
  if not exists (select 1 from profiles where id = auth.uid() and role = 'teacher') then raise exception 'Only teachers can copy sets'; end if;
  if not can_view_set(p_set) then raise exception 'Set not found'; end if;
  select * into s from study_sets where id = p_set;
  select institution_id into inst from profiles where id = auth.uid();
  insert into study_sets (owner_id, institution_id, subject_id, level_code, title, description, language, translation_lang, units, visibility)
  values (auth.uid(), inst, s.subject_id, s.level_code, left('Copy of ' || s.title, 120), s.description, s.language, s.translation_lang, s.units, 'private')
  returning id into nid;
  insert into set_items (set_id, position, kind, unit, also_units, term, meaning, example, translation, syllables, image_url, anim_url, audio_url, choices, answer)
  select nid, position, kind, unit, also_units, term, meaning, example, translation, syllables, image_url, anim_url, audio_url, choices, answer
  from set_items where set_id = p_set;
  return nid;
end $$;

-- Admin: merge a duplicate school into another.
create or replace function public.merge_institutions(p_from uuid, p_into uuid)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not exists (select 1 from profiles where id = auth.uid() and is_admin) then raise exception 'Admins only'; end if;
  if p_from = p_into then return; end if;
  update profiles   set institution_id = p_into where institution_id = p_from;
  update classes    set institution_id = p_into where institution_id = p_from;
  update study_sets set institution_id = p_into where institution_id = p_from;
  delete from institutions where id = p_from;
end $$;

