-- ---------- Study sets ----------
create table if not exists public.study_sets (
  id               uuid primary key default gen_random_uuid(),
  owner_id         uuid default auth.uid() references public.profiles(id) on delete set null,  -- null = platform set
  author_name      text not null default '',
  institution_id   uuid references public.institutions(id) on delete set null,
  subject_id       int  not null references public.subjects(id),
  level_code       text not null default 'any' references public.levels(code),
  title            text not null check (length(trim(title)) between 2 and 120),
  description      text not null default '' check (length(description) <= 1000),
  language         text not null default 'en' check (language ~ '^[a-z]{2,3}(-[A-Za-z]{2,4})?$'),
  translation_lang text not null default '' check (translation_lang = '' or translation_lang ~ '^[a-z]{2,3}(-[A-Za-z]{2,4})?$'),
  units            jsonb not null default '[]'::jsonb check (jsonb_typeof(units) = 'array'),   -- [{"u":1,"name":"..."}]
  visibility       text not null default 'private' check (visibility in ('private','public')),
  term_count       int  not null default 0,
  question_count   int  not null default 0,
  cover_url        text not null default '',
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
alter table public.study_sets add column if not exists cover_url text not null default '';
create index if not exists sets_public_idx on public.study_sets (visibility, subject_id, level_code);
create index if not exists sets_owner_idx  on public.study_sets (owner_id);

create table if not exists public.set_items (
  id          uuid primary key default gen_random_uuid(),
  set_id      uuid not null references public.study_sets(id) on delete cascade,
  position    int  not null default 0,
  kind        text not null default 'term' check (kind in ('term','mcq','tf')),
  unit        int  not null default 1 check (unit between 0 and 999),
  also_units  int[] not null default '{}',
  term        text not null check (length(trim(term)) between 1 and 500),     -- the term, or the question
  meaning     text not null default '' check (length(meaning) <= 1500),       -- definition, or explanation
  example     text not null default '' check (length(example) <= 600),
  translation text not null default '' check (length(translation) <= 300),
  syllables   text not null default '' check (length(syllables) <= 200),
  image_url   text not null default '' check (image_url = '' or image_url ~ '^(https://|assets/)'),
  anim_url    text not null default '' check (anim_url  = '' or anim_url  ~ '^(https://|assets/)'),
  audio_url   text not null default '' check (audio_url = '' or audio_url ~ '^(https://|assets/)'),
  choices     jsonb not null default '[]'::jsonb check (jsonb_typeof(choices) = 'array'),
  answer      int,
  created_at  timestamptz not null default now(),
  constraint set_items_shape check (
       (kind = 'term' and length(trim(meaning)) > 0)
    or (kind = 'mcq'  and jsonb_array_length(choices) between 2 and 6 and answer >= 0 and answer < jsonb_array_length(choices))
    or (kind = 'tf'   and answer in (0,1)))
);
create index if not exists items_set_idx on public.set_items (set_id, position);

create table if not exists public.class_sets (
  class_id    uuid not null references public.classes(id) on delete cascade,
  set_id      uuid not null references public.study_sets(id) on delete cascade,
  assigned_at timestamptz not null default now(),
  primary key (class_id, set_id)
);
create index if not exists class_sets_set_idx on public.class_sets (set_id);

