-- ---------- Media bucket (pictures and audio teachers upload) ----------
do $$
begin
  if exists (select 1 from pg_namespace where nspname = 'storage') then
    insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
    values ('media', 'media', true, 5242880,
            array['image/png','image/jpeg','image/gif','image/webp','audio/mpeg','audio/mp4','audio/x-m4a','audio/wav','audio/ogg','audio/webm'])
    on conflict (id) do nothing;
    execute 'drop policy if exists "teachers upload media to own folder" on storage.objects';
    execute $p$create policy "teachers upload media to own folder" on storage.objects for insert to authenticated
      with check (bucket_id = 'media' and (storage.foldername(name))[1] = auth.uid()::text and public.is_teacher())$p$;
    execute 'drop policy if exists "teachers delete own media" on storage.objects';
    execute $p$create policy "teachers delete own media" on storage.objects for delete to authenticated
      using (bucket_id = 'media' and (storage.foldername(name))[1] = auth.uid()::text)$p$;
  end if;
end $$;

