create table if not exists public.people (
  id uuid primary key default gen_random_uuid(),
  name text not null check (length(btrim(name)) between 1 and 120),
  kind text not null default 'person' check (kind in ('person','unknown','proverb','book','film','group')),
  born text not null default '', died text not null default '', nationality text not null default '',
  known_for text not null default '', wiki_url text not null default '', emoji text not null default '', notes text not null default '',
  created_at timestamptz not null default now(), updated_at timestamptz not null default now());
create unique index if not exists people_name_key on public.people (lower(btrim(name)));
alter table public.people enable row level security;
drop policy if exists "anyone reads people" on public.people;
create policy "anyone reads people" on public.people for select to anon, authenticated using (true);
