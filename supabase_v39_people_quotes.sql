create or replace function public.is_quote_editor() returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from profiles where id = auth.uid() and (role = 'teacher' or is_admin))
$$;
grant execute on function public.is_quote_editor() to authenticated;

-- the parent's checklist: every quote (a "Saying", or anything in Life Quotes / Famous Sayings), with its person
drop function if exists public.quote_review();
create function public.quote_review()
returns table (word_id uuid, quote text, author text, audio_url text, min_age int, sets text, unit_names text,
               person_id uuid, person text, person_kind text, role text, status text, work text, source_url text, note text, checked_at timestamptz)
language sql stable security definer set search_path = public as $$
  with q as (
    select w.* from words w
    where public.is_quote_editor()
      and ('Saying' = any(w.tags) or exists (select 1 from set_entries e where e.word_id = w.id
           and e.set_id in ('00000000-0000-4000-8000-000000009007', '00000000-0000-4000-8000-000000005a1d'))))
  select q.id, q.headword, coalesce(q.author, ''), coalesce(q.audio_url, ''), q.min_age,
         coalesce((select string_agg(distinct s.title, ', ') from set_entries e join study_sets s on s.id = e.set_id where e.word_id = q.id), ''),
         coalesce((select string_agg(distinct coalesce(u->>'name', ''), ', ')
                   from set_entries e join study_sets s on s.id = e.set_id
                   cross join lateral jsonb_array_elements(case when jsonb_typeof(s.units) = 'array' then s.units else '[]'::jsonb end) u
                   where e.word_id = q.id and (u->>'u')::int = e.unit), ''),
         p.id, coalesce(p.name, ''), coalesce(p.kind, ''), coalesce(l.role, ''), coalesce(l.status, ''), coalesce(l.work, ''), coalesce(l.source_url, ''), coalesce(l.note, ''), l.checked_at
  from q
  left join lateral (select * from quote_people x where x.word_id = q.id order by (x.role = 'misattributed'), x.checked_at desc nulls last limit 1) l on true
  left join people p on p.id = l.person_id
  order by (select min(e.position) from set_entries e where e.word_id = q.id and e.set_id = '00000000-0000-4000-8000-000000009007') nulls last, q.headword
$$;
grant execute on function public.quote_review() to authenticated;

-- link a quote to one person (replaces its links). An empty name removes the link.
drop function if exists public.set_quote_person(uuid, text, text, text, text, text);
create or replace function public.set_quote_person(p_word uuid, p_name text, p_role text default 'said', p_status text default 'verified',
                                                   p_source text default '', p_note text default '', p_work text default '')
returns uuid language plpgsql security definer set search_path = public as $$
declare v_person uuid; v_name text := btrim(coalesce(p_name, '')); v_kind text;
begin
  if not public.is_quote_editor() then raise exception 'Only the parent can check quotes.'; end if;
  if not exists (select 1 from words where id = p_word) then raise exception 'Quote not found.'; end if;
  if length(v_name) > 120 then raise exception 'Name is too long.'; end if;
  if p_role not in ('said','attributed','misattributed','popularized','proverb') then raise exception 'Unknown link type.'; end if;
  if p_status not in ('unchecked','verified','disputed') then raise exception 'Unknown status.'; end if;
  delete from quote_people where word_id = p_word;
  if v_name = '' then update words set author = '' where id = p_word; return null; end if;
  v_kind := case when lower(v_name) = 'unknown' then 'unknown' when v_name ilike '%proverb%' then 'proverb' else 'person' end;
  insert into people (name, kind) values (v_name, v_kind) on conflict do nothing;
  select id into v_person from people where lower(btrim(name)) = lower(v_name);
  insert into quote_people (word_id, person_id, role, status, work, source_url, note, checked_by, checked_at)
  values (p_word, v_person, p_role, p_status, left(btrim(coalesce(p_work, '')), 120), left(coalesce(p_source, ''), 500), left(coalesce(p_note, ''), 1000), auth.uid(),
          case when p_status = 'unchecked' then null else now() end);
  update words set author = case when v_kind = 'unknown' or p_role = 'misattributed' then '' else (select name from people where id = v_person) || case when btrim(coalesce(p_work, '')) <> '' then ' · ' || left(btrim(p_work), 120) else '' end end
  where id = p_word;
  return v_person;
end $$;
grant execute on function public.set_quote_person(uuid, text, text, text, text, text, text) to authenticated;

-- edit a person's details (a rename also renames the author on their quotes)
create or replace function public.save_person(p_id uuid, p_name text, p_kind text, p_born text, p_died text, p_nationality text,
                                              p_known_for text, p_wiki text, p_emoji text, p_notes text)
returns void language plpgsql security definer set search_path = public as $$
declare v_old text;
begin
  if not public.is_quote_editor() then raise exception 'Only the parent can edit people.'; end if;
  if btrim(coalesce(p_name, '')) = '' then raise exception 'Give the person a name.'; end if;
  if p_kind not in ('person','unknown','proverb','book','film','group') then raise exception 'Unknown kind.'; end if;
  if exists (select 1 from people where lower(btrim(name)) = lower(btrim(p_name)) and id <> p_id) then raise exception 'Someone with that name already exists.'; end if;
  select name into v_old from people where id = p_id;
  if v_old is null then raise exception 'Person not found.'; end if;
  update people set name = btrim(p_name), kind = p_kind, born = left(coalesce(p_born, ''), 40), died = left(coalesce(p_died, ''), 40),
         nationality = left(coalesce(p_nationality, ''), 80), known_for = left(coalesce(p_known_for, ''), 200), wiki_url = left(coalesce(p_wiki, ''), 300),
         emoji = left(coalesce(p_emoji, ''), 8), notes = left(coalesce(p_notes, ''), 1000), updated_at = now()
  where id = p_id;
  update words w set author = case when p_kind = 'unknown' then '' else btrim(p_name) || case when l.work <> '' then ' · ' || l.work else '' end end
  from quote_people l where l.word_id = w.id and l.person_id = p_id and l.role <> 'misattributed';
end $$;
grant execute on function public.save_person(uuid, text, text, text, text, text, text, text, text, text) to authenticated;

