  status text not null default 'unchecked' check (status in ('unchecked','verified','disputed')),
  work text not null default '', source_url text not null default '', note text not null default '',
  checked_by uuid references public.profiles(id) on delete set null, checked_at timestamptz,
  primary key (word_id, person_id));
