--   * table word_partners: the words that go with a word — adjectives (heavy rain), adverbs (rain heavily),
--     verbs (the rain stops), nouns, little words (laugh at) and idioms/phrasal verbs (Raining cats and dogs),
--     each linked to its dictionary word when there is one
