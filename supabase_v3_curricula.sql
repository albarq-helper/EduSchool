-- Which curricula each school or university follows (one or more).
create table if not exists public.institution_curricula (
  institution_id uuid not null references public.institutions(id) on delete cascade,
  curriculum_id  int  not null references public.curricula(id) on delete cascade,
  primary key (institution_id, curriculum_id)
);
create index if not exists inst_curr_curr_idx on public.institution_curricula (curriculum_id);

alter table public.profiles   add column if not exists curriculum_id int references public.curricula(id) on delete set null;
alter table public.classes    add column if not exists curriculum_id int references public.curricula(id) on delete set null;
alter table public.study_sets add column if not exists curriculum_id int references public.curricula(id) on delete set null;
create index if not exists sets_curr_idx on public.study_sets (curriculum_id);

-- A teacher may manage the curricula of their own school; the admin of any school.
create or replace function public.can_manage_institution(p_inst uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from profiles where id = auth.uid()
                 and (is_admin or (role = 'teacher' and institution_id = p_inst)));
$$;

-- Sign-up now also records the curriculum, and links it to the school when
-- a teacher signs up or the school has no curriculum yet.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
declare m jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb); inst uuid; lvl text; cur int;
        is_t boolean := (m->>'role') = 'teacher';
begin
  insert into profiles (id, full_name, role)
  values (new.id, coalesce(m->>'full_name', ''), case when is_t then 'teacher' else 'student' end)
  on conflict (id) do nothing;
  if (m->>'institution_id') ~ '^[0-9a-f-]{36}$' then
    select id into inst from institutions where id = (m->>'institution_id')::uuid;
  end if;
  if inst is null and coalesce(m->>'institution_name','') <> '' then
    inst := institution_id_for(m->>'institution_name', m->>'institution_kind', m->>'institution_country', m->>'institution_city', new.id);
  end if;
  select code into lvl from levels where code = m->>'level_code';
  if (m->>'curriculum_id') ~ '^[0-9]{1,9}$' then
    select id into cur from curricula where id = (m->>'curriculum_id')::int;
  end if;
  update profiles set institution_id = inst, level_code = lvl, curriculum_id = cur where id = new.id;
  if inst is not null and cur is not null
     and (is_t or not exists (select 1 from institution_curricula where institution_id = inst)) then
    insert into institution_curricula values (inst, cur) on conflict do nothing;
  end if;
  return new;
end $$;

-- Copies keep the curriculum.
create or replace function public.copy_set(p_set uuid)
returns uuid language plpgsql security definer set search_path = public as $$
declare s study_sets%rowtype; nid uuid; inst uuid;
begin
  if not exists (select 1 from profiles where id = auth.uid() and role = 'teacher') then raise exception 'Only teachers can copy sets'; end if;
  if not can_view_set(p_set) then raise exception 'Set not found'; end if;
  select * into s from study_sets where id = p_set;
  select institution_id into inst from profiles where id = auth.uid();
  insert into study_sets (owner_id, institution_id, subject_id, level_code, curriculum_id, title, description, language, translation_lang, units, visibility)
  values (auth.uid(), inst, s.subject_id, s.level_code, s.curriculum_id, left('Copy of ' || s.title, 120), s.description, s.language, s.translation_lang, s.units, 'private')
  returning id into nid;
  insert into set_items (set_id, position, kind, unit, also_units, term, meaning, example, translation, syllables, image_url, anim_url, audio_url, choices, answer)
  select nid, position, kind, unit, also_units, term, meaning, example, translation, syllables, image_url, anim_url, audio_url, choices, answer
  from set_items where set_id = p_set;
  return nid;
end $$;

-- Merging schools also merges their curricula.
create or replace function public.merge_institutions(p_from uuid, p_into uuid)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not exists (select 1 from profiles where id = auth.uid() and is_admin) then raise exception 'Admins only'; end if;
  if p_from = p_into then return; end if;
  insert into institution_curricula (institution_id, curriculum_id)
    select p_into, curriculum_id from institution_curricula where institution_id = p_from on conflict do nothing;
  update profiles   set institution_id = p_into where institution_id = p_from;
  update classes    set institution_id = p_into where institution_id = p_from;
  update study_sets set institution_id = p_into where institution_id = p_from;
  delete from institutions where id = p_from;
end $$;

-- ---------- Row Level Security ----------
alter table public.curricula enable row level security;
alter table public.institution_curricula enable row level security;

drop policy if exists "anyone reads curricula" on public.curricula;
create policy "anyone reads curricula" on public.curricula for select to anon, authenticated using (true);
drop policy if exists "admin manages curricula" on public.curricula;
create policy "admin manages curricula" on public.curricula for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "anyone reads school curricula" on public.institution_curricula;
create policy "anyone reads school curricula" on public.institution_curricula for select to anon, authenticated using (true);
drop policy if exists "school teachers add curricula" on public.institution_curricula;
create policy "school teachers add curricula" on public.institution_curricula for insert to authenticated
  with check (public.can_manage_institution(institution_id));
drop policy if exists "school teachers remove curricula" on public.institution_curricula;
create policy "school teachers remove curricula" on public.institution_curricula for delete to authenticated
  using (public.can_manage_institution(institution_id));

revoke all on public.curricula, public.institution_curricula from anon;
grant select on public.curricula, public.institution_curricula to anon;
grant select, insert, update, delete on public.curricula, public.institution_curricula to authenticated;

