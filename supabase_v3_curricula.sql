-- Helper Academy — v3: curricula
-- Run AFTER supabase_v2_global.sql (safe to run more than once).
-- A curriculum (Saudi Ministry of Education, American, British, IB …)
-- can be followed by many schools, and a school can follow several.
-- Students, classes and study sets each follow one curriculum
-- (or none, meaning "any curriculum").
-- =====================================================================

create table if not exists public.curricula (
  id          int primary key generated by default as identity,
  code        text not null unique check (code ~ '^[a-z0-9-]{2,30}$'),
  name        text not null unique check (length(trim(name)) between 2 and 100),
  short_name  text not null check (length(trim(short_name)) between 2 and 30),
  country     text not null default '' check (length(country) <= 60),
  sort        int  not null default 100
);

