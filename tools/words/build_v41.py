#!/usr/bin/env python3
"""Build supabase_v41_quote_values.sql: Quotes & Sayings sorted by purpose (values), and the value words
(kindness, patience, hard work, lazy, rude, …) in the dictionary with ≈ similar and ⇄ opposite links."""
import os, sys, json, collections
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.join(here, "..", ".."); sys.path.insert(0, here)
from values import VALUES, ORDER, NEW, WORDS
from families import THEMES, TYPES
q = lambda s: "'" + str(s).replace("'", "''") + "'"
arr = lambda a: "array[" + ",".join(q(t) for t in a) + "]::text[]"
SET = "00000000-0000-4000-8000-000000009007"; EXP = "00000000-0000-4000-8000-00000000e5f1"
QV = json.load(open(os.path.join(here, "quote_values.json")))
assert set(QV.values()) <= set(VALUES), set(QV.values()) - set(VALUES)
unit_of = {k: n + 1 for n, k in enumerate(ORDER)}
units = [{"u": unit_of[k], "name": VALUES[k][0]} for k in ORDER]
new = []
for line in NEW.strip().splitlines():
    p = line.split("|"); assert len(p) == 9, line
    h, t, th, emo, syl, pron, mean, ex, tr = p
    assert syl.replace("-", "") == h.lower(), "syllables: " + h
    assert "[" in ex, "example: " + h
    new.append(dict(h=h, emo=emo, syl=syl, pron=pron, mean=mean, ex=ex, tr=tr, base=[TYPES[t]] + [THEMES[c] for c in th.split(";")]))
newh = {n["h"].lower() for n in new}
tags = collections.defaultdict(list)
for k, (good, bad, extra) in WORDS.items():
    name, sim, pair, gs, bs, _ = VALUES[k]
    g = [w.replace("_", " ") for w in good.split()]; b = [w.replace("_", " ") for w in bad.split()]; e = [w.replace("_", " ") for w in extra.split()]
    for w in g + e: tags[w].append(f"≈ {sim}")
    for w in g: tags[w].append(f"⇄ {pair}: {gs}")
    for w in b: tags[w].append(f"⇄ {pair}: {bs}")
    if len(b) >= 2:
        for w in b: tags[w].append(f"≈ {bs.capitalize()}")
for w in ["Quit"]: tags[w].append("⇄ Give up vs. keep going: give up")
for n in new: assert n["h"] in tags, "new word without a value: " + n["h"]
qtags = {}
for quote, k in QV.items():
    name, sim, pair, gs, bs, extra = VALUES[k]
    qtags[quote] = ([f"≈ {sim}", f"⇄ {pair}: {gs}"] if sim else []) + extra
cnt = collections.Counter(QV.values())
sql = f"""-- =====================================================================
-- Helper Academy — v41: quotes sorted by purpose, and value words with similar words and opposites
--   * Quotes & Sayings gets {len(units)} units by purpose ({", ".join(f"{VALUES[k][0]} {cnt[k]}" for k in ORDER)})
--   * every quote gets its value's ≈ group and the good side of its ⇄ pair (e.g. "⇄ Hard-working vs. lazy: hard-working"),
--     so a word on the other side (lazy, rude, impatient) finds the quotes that teach the lesson
--   * {len(new)} new dictionary words (kindness, patience, hard work, lazy, honest, rude, …), with meaning,
--     example and Arabic, in Word Explorer unit 4 "Values & character"
--   * {len(tags)} words get value tags (≈ similar group, ⇄ opposite side)
-- Generated by tools/words/build_v41.py from values.py and quote_values.json. Safe to re-run. Run AFTER v40.
-- =====================================================================
create or replace function pg_temp.add_tags(p_head text, p_tags text[]) returns int language plpgsql as $$
declare n int;
begin
  update public.words w set tags = (select array(select distinct t from unnest(w.tags || p_tags) t order by t)), updated_at = now()
  where w.lang = 'en' and lower(w.headword) = lower(p_head) and w.sense = '';
  get diagnostics n = row_count;
  update public.set_entries e set tags = (select array(select distinct t from unnest(e.tags || p_tags) t order by t))
  where e.tags is not null and e.word_id in (select id from public.words where lang = 'en' and lower(headword) = lower(p_head) and sense = '');
  return n;
end $$;

-- new value words
insert into public.words (lang, headword, sense, meaning, example, translation, syllables, pronunciation, emoji, tags, owner_id)
select 'en', v.h, '', v.m, v.e, v.t, v.s, v.p, v.j, '{{}}'::text[],
       (select p.id from public.profiles p join auth.users u on u.id = p.id where u.email = 'albarq2000@hotmail.com')
from (values
""" + ",\n".join(f"  ({q(n['h'])}, {q(n['mean'])}, {q(n['ex'])}, {q(n['tr'])}, {q(n['syl'])}, {q(n['pron'])}, {q(n['emo'])})" for n in new) + """
) as v(h, m, e, t, s, p, j)
on conflict (lang, lower(headword), sense) do nothing;

-- value tags on words (new words also get their word type and themes)
select count(*) filter (where n = 0) as words_not_found from (values
""" + ",\n".join(f"  (pg_temp.add_tags({q(h)}, {arr(next((n['base'] for n in new if n['h'] == h), []) + t)}))" for h, t in tags.items()) + f"""
) as r(n);

-- Word Explorer: unit 4 "Values & character"
update public.study_sets set units = (select jsonb_agg(u order by (u->>'u')::int) from (
    select u from jsonb_array_elements(units) u where (u->>'u')::int <> 4 union all select '{{"u":4,"name":"Values & character"}}'::jsonb) x)
 where id = '{EXP}';
insert into public.set_entries (id, set_id, position, kind, unit, also_units, word_id)
select ('00000000-0000-4000-8000-' || lpad(to_hex(x.k), 8, '0') || 'e5f1')::uuid, '{EXP}', x.k, 'term', 4, '{{}}', w.id
from (values
""" + ",\n".join(f"  ({2000 + i}, {q(n['h'].lower())})" for i, n in enumerate(new)) + f"""
) as x(k, hw)
join public.words w on w.lang = 'en' and lower(w.headword) = x.hw and w.sense = ''
on conflict (id) do nothing;

-- Quotes & Sayings: units by purpose
update public.study_sets set units = {q(json.dumps(units, ensure_ascii=False))}::jsonb where id = '{SET}';
update public.set_entries e set unit = x.u, also_units = '{{}}'
from (values
""" + ",\n".join(f"  ({q(quote.lower())}, {unit_of[k]})" for quote, k in QV.items()) + f"""
) as x(hw, u), public.words w
where e.set_id = '{SET}' and w.id = e.word_id and lower(w.headword) = x.hw;
update public.set_entries set unit = {unit_of['X']} where set_id = '{SET}' and unit > {len(units)};

-- value tags on quotes
select count(*) filter (where n = 0) as quotes_not_found from (values
""" + ",\n".join(f"  (pg_temp.add_tags({q(quote)}, {arr(t)}))" for quote, t in qtags.items() if t) + f"""
) as r(n);

-- check
select (select count(*) from public.set_entries where set_id = '{SET}') as quotes,
       (select count(distinct unit) from public.set_entries where set_id = '{SET}') as units_used,
       (select count(*) from public.set_entries where set_id = '{EXP}' and unit = 4) as value_words,
       (select count(*) from public.words where lang = 'en' and '⇄ Hard-working vs. lazy: hard-working' = any(tags) and 'Saying' = any(tags)) as hard_work_quotes;
"""
open(os.path.join(root, "supabase_v41_quote_values.sql"), "w").write(sql)
print("new words", len(new), "tagged words", len(tags), "quotes", len(QV), dict(cnt))
