#!/usr/bin/env python3
"""Build supabase_v31_famous_sayings.sql from sayings.py."""
import os, sys
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.join(here, "..", "..")
sys.path.insert(0, here)
from sayings import SAY, SAY_UNITS, STOP
from families import THEMES

q = lambda s: "'" + s.replace("'", "''") + "'"
arr = lambda a: "array[" + ",".join(q(t) for t in a) + "]::text[]"
SET = "00000000-0000-4000-8000-000000005a1d"
rows = []
for line in SAY.strip().splitlines():
    p = line.split("|"); assert len(p) == 8, line
    u, s, a, e, m, ar, eq, tg = p
    tags = ["Saying"] + [THEMES.get(t.strip(), t.strip()) for t in tg.split(";") if t.strip()]
    rows.append((int(u), s, a, e, m, ar, eq, tags))
assert len({r[1].lower() for r in rows}) == len(rows)

v29 = open(os.path.join(root, "supabase_v29_phrases_idioms.sql")).read()
fn = v29[v29.index("create or replace function public.save_set_items"):v29.index("grant execute on function public.save_set_items(uuid, jsonb, uuid[]) to authenticated;")]
fn = fn.replace("'literal','literal_tr','equivalent'];", "'literal','literal_tr','equivalent','author'];")
fn = fn.replace("        equivalent = null,\n", "        equivalent = null,\n        author = null,\n")
assert "'author'];" in fn and "author = null" in fn

owner = "(select p.id from public.profiles p join auth.users u on u.id = p.id where u.email = 'albarq2000@hotmail.com')"
units = "'[" + ",".join('{"u": %d, "name": "%s"}' % (k + 1, n) for k, n in enumerate(SAY_UNITS)) + "]'::jsonb"
out = [f"""-- =====================================================================
-- Helper Academy — v31: Famous Sayings
--   * new word field "author" (who said it, and where) on words, set_entries, set_items and save_set_items
--   * public set "Famous Sayings" ({len(rows)}), a Story builder box of kind 'sayings':
--     the student adds a saying to a scene and chooses who says it (a character, or a voice-over)
--   * each saying is linked to the dictionary words it uses (word_partners kind 'saying'), both ways
-- Generated by tools/words/build_v31.py from tools/words/sayings.py. Safe to re-run. Run AFTER v30.
-- =====================================================================
alter table public.words add column if not exists author text not null default '';
alter table public.set_entries add column if not exists author text;

create or replace view public.set_items with (security_invoker = on) as
select e.id, e.set_id, e.position, e.kind, e.unit, e.also_units,
       coalesce(e.term, w.headword) as term,
       coalesce(e.meaning, w.meaning, '') as meaning,
       coalesce(e.example, w.example, '') as example,
       coalesce(e.translation, w.translation, '') as translation,
       coalesce(e.syllables, w.syllables, '') as syllables,
       coalesce(e.image_url, w.image_url, '') as image_url,
       coalesce(e.anim_url, w.anim_url, '') as anim_url,
       coalesce(e.audio_url, w.audio_url, '') as audio_url,
       e.choices, e.answer, e.created_at,
       coalesce(e.pronunciation, w.pronunciation, '') as pronunciation,
       coalesce(e.sound_hint, w.sound_hint, '') as sound_hint,
       coalesce(e.video_url, w.video_url, '') as video_url,
       coalesce(e.emoji, w.emoji, '') as emoji,
       coalesce(e.tags, w.tags, '{{}}') as tags,
       e.word_id, coalesce(w.sense, '') as sense,
       (e.word_id is not null and e.meaning is not null) as set_meaning,
       coalesce(e.literal, w.literal, '') as literal,
       coalesce(e.literal_tr, w.literal_tr, '') as literal_tr,
       coalesce(e.equivalent, w.equivalent, '') as equivalent,
       coalesce(e.author, w.author, '') as author
from public.set_entries e left join public.words w on w.id = e.word_id;
grant select on public.set_items to anon, authenticated;

{fn}grant execute on function public.save_set_items(uuid, jsonb, uuid[]) to authenticated;

-- partners may now also be "a famous saying that uses this word"
alter table public.word_partners drop constraint if exists word_partners_kind_check;
alter table public.word_partners add constraint word_partners_kind_check
  check (kind in ('adjective','adverb','verb','noun','preposition','idiom','saying'));

alter table public.study_sets drop constraint if exists study_sets_story_box_check;
alter table public.study_sets add constraint study_sets_story_box_check check (story_box is null or story_box in ('link', 'words', 'sayings'));

insert into public.study_sets (id, owner_id, author_name, institution_id, subject_id, level_code, title, description,
                               language, translation_lang, units, visibility, story_box)
select '{SET}', {owner}, 'Ab', null, 1, 'any', 'Famous Sayings',
  'Famous lines from writers, scientists, leaders and proverbs, with who said them, what they mean, and the Arabic saying with the same idea.',
  'en', 'ar', {units}, 'public', 'sayings'
on conflict (id) do update set title = excluded.title, description = excluded.description, units = excluded.units, story_box = excluded.story_box;

insert into public.words (lang, headword, sense, meaning, example, translation, syllables, pronunciation, emoji, equivalent, author, tags, owner_id)
select 'en', v.h, '', v.m, '', v.t, '', '', v.j, v.eq, v.a, v.tg, {owner}
from (values
"""]
out.append(",\n".join(f"  ({q(s)}, {q(m)}, {q(ar)}, {q(e)}, {q(eq)}, {q(a)}, {arr(tg)})" for u, s, a, e, m, ar, eq, tg in rows))
out.append(""") as v(h, m, t, j, eq, a, tg)
on conflict (lang, lower(headword), sense) do update set author = excluded.author, equivalent = excluded.equivalent;

insert into public.set_entries (id, set_id, position, kind, unit, also_units, word_id)
select x.id::uuid, '""" + SET + """', x.k, 'term', x.u, '{}', w.id
from (values
""")
out.append(",\n".join(f"  ({q(SET[:24] + '0001' + SET[-4:] + format(k + 1, '04x'))}, {k + 1}, {r[0]}, {q(r[1].lower())})" for k, r in enumerate(rows)))
out.append(""") as x(id, k, u, hw)
join public.words w on w.lang = 'en' and lower(w.headword) = x.hw and w.sense = ''
on conflict (id) do nothing;

-- link each saying to the dictionary words in it (not to other sayings, idioms or phrasal verbs)
insert into public.word_partners (word_id, kind, phrase, partner, partner_word_id, position, owner_id)
select distinct on (d.id, s.id) d.id, 'saying', s.headword, d.headword, s.id, 900, """ + owner + """
from public.set_entries e join public.words s on s.id = e.word_id
cross join lateral regexp_split_to_table(lower(s.headword), '[^a-z]+') tok
join public.words d on d.lang = 'en' and d.sense = '' and lower(d.headword) = tok and d.id <> s.id
where e.set_id = '""" + SET + """' and length(tok) >= 4 and tok <> all (array[""" + ",".join(q(w) for w in STOP) + """])
  and not (d.tags && array['Saying','Idiom','Phrasal verb'])
on conflict (word_id, lower(phrase)) do nothing;

-- check
select (select count(*) from public.set_items where set_id = '""" + SET + """') as sayings,
       (select count(*) from public.set_items where set_id = '""" + SET + """' and author <> '') as with_author,
       (select count(*) from public.word_partners where kind = 'saying') as word_links,
       (select string_agg(distinct partner, ', ') from public.word_partners where kind = 'saying') as linked_words;
""")
open(os.path.join(root, "supabase_v31_famous_sayings.sql"), "w").write("".join(out))
print("sayings", len(rows))
