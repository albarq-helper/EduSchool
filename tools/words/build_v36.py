#!/usr/bin/env python3
"""Build supabase_v36_life_quotes_ages.sql: minimum ages + the Life Quotes set (718 voice clips in assets/audio/quotes)."""
import os, json
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.join(here, "..", "..")
M = json.load(open(os.path.join(here, "life_quotes.json")))
q = lambda s: "'" + str(s).replace("'", "''") + "'"
SET = "00000000-0000-4000-8000-000000009007"
units = []
for m in M:
    if not any(u["u"] == m["unit"] for u in units): units.append({"u": m["unit"], "name": m["unit_name"]})
owner = "(select p.id from public.profiles p join auth.users u on u.id = p.id where u.email = 'albarq2000@hotmail.com')"
sql = f"""-- =====================================================================
-- Helper Academy — v36: minimum ages, and the Life Quotes set
--   * minimum age on words (min_age), on set links (set_entries.min_age) and on sets (study_sets.min_age)
--   * a student's birth year (profiles.birth_year); the parent sets it (set_student_birth_year)
--   * public.viewer_age(): teachers and admins see everything; a student sees items up to her age;
--     a student with no birth year sees only items without a minimum age
--   * the dictionary, the set_items view and the list of sets hide what is above the viewer's age
--   * new set "Life Quotes" ({len(M)} quotes with the narrator's voice, from 5 videos), a Story builder sayings box;
--     {sum(m['age'] > 0 for m in M)} quotes are 18+
-- Generated by tools/words/build_v36.py. Safe to re-run. Run AFTER v35.
-- =====================================================================
alter table public.words add column if not exists min_age int not null default 0 check (min_age between 0 and 21);
alter table public.set_entries add column if not exists min_age int check (min_age between 0 and 21);
alter table public.study_sets add column if not exists min_age int not null default 0 check (min_age between 0 and 21);
alter table public.profiles add column if not exists birth_year int check (birth_year between 1900 and 2100);

create or replace function public.viewer_age() returns int language sql stable security definer set search_path = public as $$
  select case when auth.uid() is null then 0
              when exists (select 1 from profiles where id = auth.uid() and (role = 'teacher' or is_admin)) then 200
              else coalesce((select extract(year from now())::int - birth_year from profiles where id = auth.uid()), 0) end
$$;
grant execute on function public.viewer_age() to anon, authenticated;

-- the parent sets the birth year of a student in one of their classes (or their own)
create or replace function public.set_student_birth_year(p_student uuid, p_year int) returns void language plpgsql security definer set search_path = public as $$
begin
  if p_year is not null and (p_year < 1900 or p_year > extract(year from now())::int) then raise exception 'Please enter a real birth year.'; end if;
  if not (p_student = auth.uid() or public.teaches(p_student) or exists (select 1 from profiles where id = auth.uid() and is_admin)) then
    raise exception 'Only this student''s teacher or parent can set the age.'; end if;
  update profiles set birth_year = p_year where id = p_student;
end $$;
grant execute on function public.set_student_birth_year(uuid, int) to authenticated;

-- the owner of a set (or an admin) sets the minimum age of one item in it
create or replace function public.set_item_min_age(p_entry uuid, p_age int) returns void language plpgsql security definer set search_path = public as $$
begin
  if p_age < 0 or p_age > 21 then raise exception 'Age must be 0 to 21.'; end if;
  if not exists (select 1 from set_entries e join study_sets s on s.id = e.set_id where e.id = p_entry and (s.owner_id = auth.uid() or exists (select 1 from profiles where id = auth.uid() and is_admin))) then
    raise exception 'Only the owner of this set can change it.'; end if;
  update set_entries set min_age = nullif(p_age, 0) where id = p_entry;
  update words w set min_age = p_age from set_entries e where e.id = p_entry and w.id = e.word_id and (w.owner_id = auth.uid() or exists (select 1 from profiles where id = auth.uid() and is_admin));
end $$;
grant execute on function public.set_item_min_age(uuid, int) to authenticated;

-- hide what is above the viewer's age
drop policy if exists "anyone reads the dictionary" on public.words;
create policy "anyone reads the dictionary" on public.words for select to anon, authenticated using (min_age <= public.viewer_age());

create or replace function public.can_view_set(p_set uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from study_sets s where s.id = p_set and
           (s.owner_id = auth.uid() or exists (select 1 from profiles where id = auth.uid() and is_admin)
            or (s.min_age <= public.viewer_age() and
                (s.visibility = 'public'
                 or exists (select 1 from class_sets cs join classes c on c.id = cs.class_id
                            where cs.set_id = s.id and (c.teacher_id = auth.uid()
                              or exists (select 1 from class_members m where m.class_id = c.id and m.student_id = auth.uid())))))));
$$;
"""
v35 = open(os.path.join(root, "supabase_v32_director.sql")).read()
view = v35[v35.index("create or replace view public.set_items"):v35.index("grant select on public.set_items to anon, authenticated;")]
view = view.replace("       coalesce(e.film, w.film, '') as film\nfrom public.set_entries e left join public.words w on w.id = e.word_id;",
                    "       coalesce(e.film, w.film, '') as film,\n       coalesce(e.min_age, w.min_age, 0) as min_age\nfrom public.set_entries e left join public.words w on w.id = e.word_id\nwhere coalesce(e.min_age, w.min_age, 0) <= public.viewer_age();")
assert "as min_age" in view and "viewer_age()" in view
sql += view + "grant select on public.set_items to anon, authenticated;\n\n"
sql += f"""-- the Life Quotes set
insert into public.study_sets (id, owner_id, author_name, institution_id, subject_id, level_code, title, description,
                               language, translation_lang, units, visibility, story_box)
select '{SET}', {owner}, 'Ab', null, 1, 'any', 'Life Quotes',
  'Short life lessons with the narrator''s voice, from five quote videos. Tap to hear each one.',
  'en', 'ar', {q(json.dumps(units))}::jsonb, 'public', 'sayings'
on conflict (id) do update set title = excluded.title, description = excluded.description, units = excluded.units, story_box = excluded.story_box;

insert into public.words (lang, headword, sense, meaning, example, translation, syllables, pronunciation, emoji, audio_url, min_age, tags, owner_id)
select distinct on (lower(v.h)) 'en', v.h, '', '', '', '', '', '', '💬', v.a, v.g, array['Saying'], {owner}
from (values
""" + ",\n".join(f"  ({q(m['text'])}, {q('assets/audio/quotes/' + m['file'])}, {m['age']})" for m in M) + f"""
) as v(h, a, g)
on conflict (lang, lower(headword), sense) do nothing;

insert into public.set_entries (id, set_id, position, kind, unit, also_units, word_id, audio_url, min_age)
select x.id::uuid, '{SET}', x.k, 'term', x.u, '{{}}', w.id, x.a, nullif(x.g, 0)
from (values
""" + ",\n".join(f"  ({q(SET[:24] + format(k + 1, '012x').replace(format(k + 1, '012x')[:4], '0001', 1)[:12])}, {k + 1}, {m['unit']}, {q(m['text'].lower())}, {q('assets/audio/quotes/' + m['file'])}, {m['age']})" for k, m in enumerate(M)) + """
) as x(id, k, u, hw, a, g)
join public.words w on w.lang = 'en' and lower(w.headword) = x.hw and w.sense = ''
on conflict (id) do update set audio_url = excluded.audio_url, min_age = excluded.min_age;

-- check
select (select count(*) from public.set_entries where set_id = '""" + SET + """') as life_quotes,
       (select count(*) from public.set_entries where set_id = '""" + SET + """' and min_age >= 18) as adult_only,
       (select count(*) from public.words where min_age >= 18) as adult_words;
"""
open(os.path.join(root, "supabase_v36_life_quotes_ages.sql"), "w").write(sql)
print("quotes", len(M))
