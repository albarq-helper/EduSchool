#!/usr/bin/env python3
"""Build supabase_v91_idioms_more.sql from idioms/b*.txt (idioms from Idioms.pdf that the site did not have yet)."""
import glob, os
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.join(here, "..", "..")
q = lambda s: "'" + s.replace("'", "''") + "'"
arr = lambda a: "array[" + ",".join(q(t) for t in a) + "]::text[]"
IDSET = "00000000-0000-4000-8000-00000000d10e"
NEW_UNITS = {8: "Colours", 9: "Time", 10: "Money & work", 11: "Love & people", 12: "Tricky situations", 13: "Everyday life"}
rows = []
for f in sorted(glob.glob(os.path.join(here, "idioms", "b?.txt"))):
    for l in open(f):
        p = l.rstrip("\n").split("|")
        if not p[0]: continue
        assert len(p) == 10, l
        h, u, e, m, ex, tr, lit, litar, eq, tg = p
        assert "[" in ex, h
        tg = tg.replace("≈ Mocking;", "").replace(";≈ Mocking", ";≈ Rude")
        tags = ["Idiom"] + [t.strip() for t in tg.split(";") if t.strip()]
        rows.append((h, int(u), e, m, ex, tr, lit, litar, eq, list(dict.fromkeys(tags))))
heads = [r[0].lower() for r in rows]; assert len(heads) == len(set(heads)), "duplicate"
owner = "'b558b8ee-2ab1-43ca-8778-db03f4bf5f38'::uuid"
out = [f"""-- =====================================================================
-- Helper Academy — v91: {len(rows)} more idioms (the ones in Idioms.pdf that the site did not have yet)
--   Added to the Idioms set in six new units. Each idiom keeps the same link tags as the first 48:
--   a theme, similar-words groups (≈), opposite sides (⇄) and meters, so it shows up next to the words with the same meaning.
-- Generated by tools/words/build_v91_idioms.py. Safe to re-run. Run AFTER v90.
-- =====================================================================
update public.study_sets set units = units || (
  select coalesce(jsonb_agg(x), '[]'::jsonb) from jsonb_array_elements('[{",".join('{"u": %d, "name": "%s"}' % (k, n) for k, n in NEW_UNITS.items())}]'::jsonb) x
   where not exists (select 1 from jsonb_array_elements(units) o where (o->>'u')::int = (x->>'u')::int))
 where id = '{IDSET}';

insert into public.words (lang, headword, sense, meaning, example, translation, syllables, pronunciation, emoji, literal, literal_tr, equivalent, tags, owner_id)
select 'en', v.h, '', v.m, v.e, v.t, '', '', v.j, v.l, v.lt, v.eq, v.tg, {owner}
from (values
"""]
out.append(",\n".join(f"  ({q(r[0])}, {q(r[3])}, {q(r[4])}, {q(r[5])}, {q(r[2])}, {q(r[6])}, {q(r[7])}, {q(r[8])}, {arr(r[9])})" for r in rows))
out.append(""") as v(h, m, e, t, j, l, lt, eq, tg)
on conflict (lang, lower(headword), sense) do nothing;

insert into public.set_entries (id, set_id, position, kind, unit, also_units, word_id)
select x.id::uuid, x.s::uuid, x.k, 'term', x.u, '{}', w.id
from (values
""")
ent = []
for k, r in enumerate(rows, start=49):
    eid = IDSET[:24] + "0001" + IDSET[-4:] + f"{k:04x}"
    ent.append(f"  ({q(eid)}, '{IDSET}', {k}, {r[1]}, {q(r[0].lower())})")
out.append(",\n".join(ent))
out.append(""") as x(id, s, k, u, hw)
join public.words w on w.lang = 'en' and lower(w.headword) = x.hw and w.sense = ''
on conflict (id) do nothing;

-- check: items per unit, and any entry whose word is not tagged Idiom (= the headword already belonged to another word)
select i.unit, count(*) as items from public.set_items i where i.set_id = '""" + IDSET + """' group by i.unit order by i.unit;
select i.term from public.set_items i where i.set_id = '""" + IDSET + """' and not ('Idiom' = any(i.tags));
""")
open(os.path.join(root, "supabase_v91_idioms_more.sql"), "w").write("".join(out))
print(len(rows), "idioms")
