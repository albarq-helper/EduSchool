#!/usr/bin/env python3
"""Build supabase_v43_feelings_wheel.sql: the feelings wheel words, with ≈ similar words, ⇄ opposites and 📶 meters."""
import os, sys, collections
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.join(here, "..", ".."); sys.path.insert(0, here)
from wheel import NEW, SIM, OPP, SCALES, FAMILIES
from families import THEMES, TYPES
q = lambda s: "'" + str(s).replace("'", "''") + "'"
arr = lambda a: "array[" + ",".join(q(t) for t in a) + "]::text[]"
FEE = "00000000-0000-4000-8000-00000000fee1"
MISSING = "Disgust, Surprise, Insecure, Submissive, Rejected, Humiliated, Hurt, Threatened, Hateful, Mad, Aggressive, Critical, Disapproval, Awful, Avoidance, Guilty, Abandoned, Bored, Intimate, Powerful, Accepted, Proud, Interested, Excited, Amazed, Confused, Startled, Overwhelmed, Inadequate, Inferior, Worthless, Insignificant, Alienated, Disrespected, Ridiculed, Embarrassed, Jealous, Resentful, Violated, Enraged, Provoked, Hostile, Infuriated, Withdrawn, Suspicious, Skeptical, Sarcastic, Judgmental, Loathing, Repugnant, Revolted, Revulsion, Detestable, Aversion, Hesitant, Remorseful, Ashamed, Ignored, Victimized, Powerless, Vulnerable, Empty, Isolated, Apathetic, Open, Playful, Sensitive, Loving, Provocative, Fulfilled, Respected, Inquisitive, Amused, Liberated, Eager, Awe, Astonished, Perplexed, Disillusioned, Dismayed, Shocked".split(", ")
new = []
for line in NEW.strip().splitlines():
    p = line.split("|"); assert len(p) == 10, line
    h, t, th, emo, syl, pron, mean, ex, tr, age = p
    assert syl.replace("-", "") == h.lower(), "syllables: " + h
    assert "[" in ex, "example: " + h
    new.append(dict(h=h, emo=emo, syl=syl, pron=pron, mean=mean, ex=ex, tr=tr, age=int(age), base=[TYPES[t]] + [THEMES[c] for c in th.split(";")]))
have = {n["h"] for n in new}
miss = [m for m in MISSING if m not in have]; extra = [h for h in have if h not in MISSING]
assert not miss and not extra, (miss, extra)
tags = collections.defaultdict(list)
for g, ws in SIM.items():
    for w in ws.split(): tags[w].append(f"≈ {g}")
for g, sides in OPP.items():
    for side, ws in sides.items():
        for w in ws.split(): tags[w].append(f"⇄ {g}: {side}")
for g, members in SCALES.items():
    for w, r in members: tags[w].append(f"📶 {g}: {'+' if r > 0 else ''}{r}")
for n in new: assert n["h"] in tags, "no links: " + n["h"]
fam_words = [(k + 8, name, w) for k, (name, ws) in enumerate(FAMILIES) for w in ws.split()]
sql = f"""-- =====================================================================
-- Helper Academy — v43: the feelings wheel (Fear, Anger, Disgust, Sad, Happy, Surprise)
--   * {len(new)} new feeling words (meaning, example, Arabic); 4 are 13+ (Intimate, Provocative, Violated, Victimized)
--   * ≈ similar groups from the wheel's inner ring, ⇄ opposites (accepted vs. rejected, interested vs. bored,
--     proud vs. ashamed, powerful vs. powerless, trusting vs. suspicious, like vs. disgusted, sure vs. confused, …)
--   * 📶 meters: new levels on Angry → Calm, Afraid → Calm, Hate ⇄ Love, Sad ⇄ Happy; new meters Ashamed ⇄ Proud, Bored → Excited
--   * "Feelings: Word Scales" gets 6 units, one per family of the wheel, with every wheel word (old and new)
-- Generated by tools/words/build_v43.py from wheel.py. Safe to re-run. Run AFTER v42.
-- =====================================================================
-- add tags to a word (and any set-specific tag override); one place per meter
create or replace function pg_temp.add_family_tags(p_head text, p_tags text[]) returns int language plpgsql as $$
declare n int;
begin
  update public.words w set tags = (
      select array(select distinct t from unnest(
        array(select t0 from unnest(w.tags) t0 where not (t0 like '📶 %' and split_part(t0, ':', 1) in (select split_part(x, ':', 1) from unnest(p_tags) x where x like '📶 %')))
        || p_tags) t order by t)), updated_at = now()
  where w.lang = 'en' and lower(w.headword) = lower(p_head) and w.sense = '';
  get diagnostics n = row_count;
  update public.set_entries e set tags = (
      select array(select distinct t from unnest(
        array(select t0 from unnest(e.tags) t0 where not (t0 like '📶 %' and split_part(t0, ':', 1) in (select split_part(x, ':', 1) from unnest(p_tags) x where x like '📶 %')))
        || p_tags) t order by t))
  where e.tags is not null and e.word_id in (select id from public.words where lang = 'en' and lower(headword) = lower(p_head) and sense = '');
  return n;
end $$;

insert into public.words (lang, headword, sense, meaning, example, translation, syllables, pronunciation, emoji, min_age, tags, owner_id)
select 'en', v.h, '', v.m, v.e, v.t, v.s, v.p, v.j, v.g, '{{}}'::text[],
       (select p.id from public.profiles p join auth.users u on u.id = p.id where u.email = 'albarq2000@hotmail.com')
from (values
""" + ",\n".join(f"  ({q(n['h'])}, {q(n['mean'])}, {q(n['ex'])}, {q(n['tr'])}, {q(n['syl'])}, {q(n['pron'])}, {q(n['emo'])}, {n['age']})" for n in new) + """
) as v(h, m, e, t, s, p, j, g)
on conflict (lang, lower(headword), sense) do nothing;

select count(*) filter (where n = 0) as words_not_found from (values
""" + ",\n".join(f"  (pg_temp.add_family_tags({q(h)}, {arr(next((n['base'] for n in new if n['h'] == h), []) + t)}))" for h, t in tags.items()) + f"""
) as r(n);

-- Feelings: Word Scales — one unit per family of the wheel
update public.study_sets set units = (select jsonb_agg(u order by (u->>'u')::int) from (
    select u from jsonb_array_elements(units) u where (u->>'u')::int < 8
    union all select x from jsonb_array_elements({q(str([{"u": k + 8, "name": n} for k, (n, _) in enumerate(FAMILIES)]).replace("'", '"'))}::jsonb) x) y)
 where id = '{FEE}';
create temp table fam(u int, hw text, k int);
insert into fam values
""" + ",\n".join(f"  ({u}, {q(w.lower())}, {3000 + i})" for i, (u, _, w) in enumerate(fam_words)) + f""";
-- words already in the set get the family as an extra unit
update public.set_entries e set also_units = (select array(select distinct x from unnest(coalesce(e.also_units, '{{}}') || array[f.u]) x where x <> e.unit order by x))
  from fam f, public.words w
 where e.set_id = '{FEE}' and w.id = e.word_id and lower(w.headword) = f.hw;
-- the others are added to the family unit
insert into public.set_entries (id, set_id, position, kind, unit, also_units, word_id)
select ('00000000-0000-4000-8000-' || lpad(to_hex(f.k), 8, '0') || 'fee1')::uuid, '{FEE}', f.k, 'term', f.u, '{{}}', w.id
from fam f join public.words w on w.lang = 'en' and lower(w.headword) = f.hw and w.sense = ''
where not exists (select 1 from public.set_entries e where e.set_id = '{FEE}' and e.word_id = w.id)
on conflict (id) do nothing;
drop table fam;

-- check
select (select count(*) from public.words where lang = 'en' and sense = '' and lower(headword) in ({", ".join(q(m.lower()) for m in MISSING)})) as wheel_words_added,
       (select count(*) from public.set_entries where set_id = '{FEE}') as feelings_set_items,
       (select count(*) from public.words where 'Bored → Excited' = any(array(select split_part(t, ':', 1) from unnest(tags) t))) as hmm;
"""
sql = sql.replace("(select count(*) from public.words where 'Bored → Excited' = any(array(select split_part(t, ':', 1) from unnest(tags) t))) as hmm",
                  "(select count(*) from public.words w, unnest(w.tags) t where t like '📶 Bored → Excited:%') as on_bored_excited_meter")
open(os.path.join(root, "supabase_v43_feelings_wheel.sql"), "w").write(sql)
print("new", len(new), "tagged", len(tags), "family links", len(fam_words))
