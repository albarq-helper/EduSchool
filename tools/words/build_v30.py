#!/usr/bin/env python3
"""Build supabase_v30_word_partners.sql from partners.py."""
import os, re, sys
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.join(here, "..", "..")
sys.path.insert(0, here)
from partners import HUB, HUB_UNITS, PARTNERS, ADVERBS
from families import THEMES, TYPES
from phrases import PV, ID

q = lambda s: "'" + s.replace("'", "''") + "'"
KIND = {"a": "adjective", "d": "adverb", "v": "verb", "n": "noun", "p": "preposition", "i": "idiom"}
idioms = {l.split("|")[1].lower(): l.split("|")[1] for l in (PV + ID).strip().splitlines() if "|" in l}
HUBSET = "00000000-0000-4000-8000-00000000c011"

hub = []
for line in HUB.strip().splitlines():
    p = line.split("|"); assert len(p) == 9, line
    u, h, t, th, e, syl, m, ex, ar = p
    assert syl.replace("-", "") == h.lower(), h; assert "[" in ex, h
    hub.append((int(u), h, [TYPES[t]] + [THEMES[c] for c in th.split(";")], e, syl, m, ex, ar))

prt = []  # (head, kind, phrase, partner, pos)
for line in PARTNERS.strip().splitlines():
    head, rest = line.split(":", 1); head = head.strip(); pos = 0
    for grp in rest.split("|"):
        k, items = grp.split(":", 1); k = k.strip(); assert k in KIND, line
        for it in items.split(","):
            it = it.strip()
            if not it: continue
            pos += 1
            if k == "i":
                assert it.lower() in idioms, "not an idiom/phrasal verb: " + it
                prt.append((head, "idiom", idioms[it.lower()], idioms[it.lower()], pos))
            else:
                parts = re.findall(r"\*([^*]+)\*", it); assert parts, "mark the partner with *stars*: " + it
                prt.append((head, KIND[k], it.replace("*", ""), " … ".join(parts), pos))
print(f"hub words {len(hub)} · words with partners {len({p[0] for p in prt})} · partners {len(prt)}")

owner = "(select p.id from public.profiles p join auth.users u on u.id = p.id where u.email = 'albarq2000@hotmail.com')"
units = "'[" + ",".join('{"u": %d, "name": "%s"}' % (k + 1, n) for k, n in enumerate(HUB_UNITS)) + "]'::jsonb"
arr = lambda a: "array[" + ",".join(q(t) for t in a) + "]::text[]"
out = [f"""-- =====================================================================
-- Helper Academy — v30: word partners (collocations) and grammar word types
--   * table word_partners: the words that go with a word — adjectives (heavy rain), adverbs (rain heavily),
--     verbs (the rain stops), nouns, little words (laugh at) and idioms/phrasal verbs (Raining cats and dogs),
--     each linked to its dictionary word when there is one
--   * new public set "Word Partners" ({len(hub)} everyday words), and partners for {len({p[0] for p in prt})} words in all ({len(prt)} partners)
--   * word types: adverbs get "Adverb"; Phrasal Verbs get "Phrasal verb"; Idioms get "Idiom"
-- Generated by tools/words/build_v30.py from tools/words/partners.py. Safe to re-run. Run AFTER v29.
-- =====================================================================
create table if not exists public.word_partners (
  id uuid primary key default gen_random_uuid(),
  word_id uuid not null references public.words(id) on delete cascade,
  kind text not null check (kind in ('adjective','adverb','verb','noun','preposition','idiom')),
  phrase text not null check (length(phrase) between 1 and 200),
  partner text not null default '',
  partner_word_id uuid references public.words(id) on delete set null,
  position int not null default 0,
  owner_id uuid default auth.uid(),
  created_at timestamptz not null default now()
);
create unique index if not exists word_partners_unique on public.word_partners (word_id, lower(phrase));
create index if not exists word_partners_partner on public.word_partners (partner_word_id);
alter table public.word_partners enable row level security;
drop policy if exists "partners readable" on public.word_partners;
create policy "partners readable" on public.word_partners for select to anon, authenticated using (true);
drop policy if exists "partners by word owner" on public.word_partners;
create policy "partners by word owner" on public.word_partners for all to authenticated
  using (public.is_admin() or exists (select 1 from public.words w where w.id = word_id and w.owner_id = auth.uid()))
  with check (public.is_admin() or exists (select 1 from public.words w where w.id = word_id and w.owner_id = auth.uid()));
grant select on public.word_partners to anon, authenticated;
grant insert, update, delete on public.word_partners to authenticated;

-- grammar word types
update public.words set tags = array_replace(tags, 'Describing', 'Adverb'), updated_at = now()
where lang = 'en' and sense = '' and headword in ({", ".join(q(a) for a in ADVERBS)}) and 'Describing' = any(tags);
update public.set_entries set tags = array_replace(tags, 'Describing', 'Adverb')
where tags is not null and word_id in (select id from public.words where lang = 'en' and headword in ({", ".join(q(a) for a in ADVERBS)}));
update public.words w set tags = array_replace(w.tags, 'Action', 'Phrasal verb'), updated_at = now()
from public.set_entries e where e.word_id = w.id and e.set_id = '00000000-0000-4000-8000-00000000f4a5' and 'Action' = any(w.tags);
update public.words w set tags = array['Idiom'] || w.tags, updated_at = now()
from public.set_entries e where e.word_id = w.id and e.set_id = '00000000-0000-4000-8000-00000000d10e' and not ('Idiom' = any(w.tags));

-- the Word Partners set
insert into public.study_sets (id, owner_id, author_name, institution_id, subject_id, level_code, title, description,
                               language, translation_lang, units, visibility, story_box)
select '{HUBSET}', {owner}, 'Ab', null, 1, 'any', 'Word Partners',
  'Everyday words and the words that go with them: heavy rain, rain heavily, make a mistake, do your homework.',
  'en', 'ar', {units}, 'public', 'words'
on conflict (id) do update set title = excluded.title, description = excluded.description, units = excluded.units;

insert into public.words (lang, headword, sense, meaning, example, translation, syllables, pronunciation, emoji, tags, owner_id)
select 'en', v.h, '', v.m, v.e, v.t, v.s, '', v.j, v.tg, {owner}
from (values
"""]
out.append(",\n".join(f"  ({q(h)}, {q(m)}, {q(ex)}, {q(ar)}, {q(syl)}, {q(e)}, {arr(tg)})" for u, h, tg, e, syl, m, ex, ar in hub))
out.append(""") as v(h, m, e, t, s, j, tg)
on conflict (lang, lower(headword), sense) do nothing;

insert into public.set_entries (id, set_id, position, kind, unit, also_units, word_id)
select x.id::uuid, '""" + HUBSET + """', x.k, 'term', x.u, '{}', w.id
from (values
""")
out.append(",\n".join(f"  ({q(HUBSET[:24] + '0001' + HUBSET[-4:] + format(k + 1, '04x'))}, {k + 1}, {u}, {q(h.lower())})" for k, (u, h, *_ ) in enumerate(hub)))
out.append(""") as x(id, k, u, hw)
join public.words w on w.lang = 'en' and lower(w.headword) = x.hw and w.sense = ''
on conflict (id) do nothing;

-- partners (linked to a dictionary word when the partner is one)
insert into public.word_partners (word_id, kind, phrase, partner, partner_word_id, position, owner_id)
select w.id, x.kind, x.phrase, x.partner,
       (select p.id from public.words p where p.lang = 'en' and p.sense = '' and p.id <> w.id
          and lower(p.headword) = lower(case when x.kind = 'idiom' then x.phrase else x.partner end) limit 1),
       x.pos, """ + owner + """
from (values
""")
out.append(",\n".join(f"  ({q(h.lower())}, {q(k)}, {q(ph)}, {q(pa)}, {pos})" for h, k, ph, pa, pos in prt))
out.append(""") as x(hw, kind, phrase, partner, pos)
join public.words w on w.lang = 'en' and lower(w.headword) = x.hw and w.sense = ''
on conflict (word_id, lower(phrase)) do update set kind = excluded.kind, partner = excluded.partner,
  partner_word_id = excluded.partner_word_id, position = excluded.position;

-- check
select (select count(*) from public.word_partners) as partners,
       (select count(distinct word_id) from public.word_partners) as words_with_partners,
       (select count(*) from public.word_partners where partner_word_id is not null) as linked_partners,
       (select count(*) from public.set_items where set_id = '""" + HUBSET + """') as hub_words,
       (select count(*) from public.words where 'Adverb' = any(tags)) as adverbs,
       (select count(*) from public.words where 'Idiom' = any(tags)) as idioms,
       (select count(*) from public.words where 'Phrasal verb' = any(tags)) as phrasal_verbs;
""")
open(os.path.join(root, "supabase_v30_word_partners.sql"), "w").write("".join(out))
