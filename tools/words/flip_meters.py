#!/usr/bin/env python3
"""v35: every meter reads bad/negative (red, left) → good/positive (green, right).
Meters whose strong end is the bad one are renamed (left = bad) and their levels negated (0 = the good end).
Updates the data sources (families.py, partners.py, phrases.py), the meter faces, and writes supabase_v35_meter_direction.sql."""
import os, re
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.join(here, "..", "..")
FLIP = {  # old name → new name (left → right)
  "Calm → Afraid": "Afraid → Calm", "Calm → Angry": "Angry → Calm", "Full → Hungry": "Hungry → Full",
  "Silent → Deafening": "Deafening → Silent", "Safe → Deadly": "Deadly → Safe", "Energetic → Exhausted": "Exhausted → Energetic",
  "Clean → Filthy": "Filthy → Clean", "Gentle → Ferocious": "Ferocious → Gentle", "Breeze → Hurricane": "Hurricane → Breeze",
  "Storm · mild → violent": "Storm · violent → mild", "Wind · gentle → howling": "Wind · howling → gentle",
  "Noise · faint → deafening": "Noise · deafening → faint", "Mistake · tiny → terrible": "Mistake · terrible → tiny",
  "Trouble · a little → serious": "Trouble · serious → a little", "Nervous · a bit → very": "Nervous · very → a bit",
  "Test · easy → hard": "Test · hard → easy", "Homework · easy → difficult": "Homework · difficult → easy",
  "Question · easy → tricky": "Question · tricky → easy",
}
neg = lambda r: str(-int(r)) if int(r) != 0 else "0"
def tagfix(s):  # "📶 Calm → Angry: +3" → "📶 Angry → Calm: -3"
    for o, n in FLIP.items():
        s = re.sub(r"📶 " + re.escape(o) + r": ([+-]?\d+)", lambda m: f"📶 {n}: {neg(m.group(1))}", s)
    return s
def edit(name, fn):
    p = os.path.join(here, name); s = open(p).read(); t = fn(s)
    if t != s: open(p, "w").write(t); print("updated", name)
# families.py: SCALES keys and their (word, rank) pairs
def fam(s):
    for o, n in FLIP.items():
        m = re.search(r'  "' + re.escape(o) + r'":\s*\((.*?)\),\n', s)
        if not m: continue
        body = re.sub(r'\("([^"]+)",\s*([+-]?\d+)\)', lambda x: f'("{x.group(1)}", {neg(x.group(2))})', m.group(1))
        s = s.replace(m.group(0), f'  "{n}": ({body}),\n')
    return tagfix(s)
edit("families.py", fam)
# partners.py: Head|meter|kind|phrase:partner:rank, …
def par(s):
    out = []
    for line in s.split("\n"):
        f = line.split("|")
        if len(f) == 4 and f[1] in FLIP:
            items = [re.sub(r":([+-]?\d+)$", lambda m: ":" + neg(m.group(1)), it.strip()) for it in f[3].split(",")]
            line = "|".join([f[0], FLIP[f[1]], f[2], ", ".join(items)])
        out.append(line)
    return "\n".join(out)
edit("partners.py", par)
edit("phrases.py", tagfix)
# meter faces: rename and negate the level keys
def faces(s):
    for o, n in FLIP.items():
        m = re.search(r'"' + re.escape(o.lower()) + r'": \{([^}]*)\}', s)
        if not m: continue
        body = re.sub(r'"([+-]?\d+)":', lambda x: f'"{neg(x.group(1))}":', m.group(1))
        s = s.replace(m.group(0), f'"{n.lower()}": {{{body}}}')
    return s
p = os.path.join(root, "js", "meter.js"); s = open(p).read(); t = faces(s)
if t != s: open(p, "w").write(t); print("updated meter faces")
# the database
q = lambda x: "'" + x.replace("'", "''") + "'"
sql = """-- =====================================================================
-- Helper Academy — v35: every meter reads bad (red, left) → good (green, right)
--   Meters whose strong end is the bad one are renamed so the bad end comes first, and their levels become negative
--   (e.g. "Calm → Angry: +3" becomes "Angry → Calm: -3"; 0 is the good end). Words, set links and word partners.
-- Generated by tools/words/flip_meters.py. Safe to re-run (a renamed meter is not renamed twice). Run AFTER v34.
-- =====================================================================
create or replace function pg_temp.flip(p_tags text[], p_old text, p_new text) returns text[] language sql immutable as $$
  select array(select case when t like '📶 ' || p_old || ':%'
                           then '📶 ' || p_new || ': ' || (-(substring(t from ':\\s*([+-]?\\d+)\\s*$'))::int)::text
                           else t end
               from unnest(p_tags) t)
$$;
"""
for o, n in FLIP.items():
    like = q("%📶 " + o + ":%")
    sql += f"""update public.words set tags = pg_temp.flip(tags, {q(o)}, {q(n)}), updated_at = now() where array_to_string(tags, '|') like {like};
update public.set_entries set tags = pg_temp.flip(tags, {q(o)}, {q(n)}) where tags is not null and array_to_string(tags, '|') like {like};
update public.word_partners set tags = pg_temp.flip(tags, {q(o)}, {q(n)}) where array_to_string(tags, '|') like {like};
"""
sql += """
-- check: nothing is left on an old name, and e.g. the Angry → Calm meter
select (select count(*) from public.words where array_to_string(tags, '|') ~ '📶 (Calm → (Afraid|Angry)|Full → Hungry|Safe → Deadly|Breeze → Hurricane):') as old_left,
       (select string_agg(headword || ' ' || split_part(t, ': ', 2), ', ' order by split_part(t, ': ', 2)::int)
          from public.words, unnest(tags) t where t like '📶 Angry → Calm:%') as angry_to_calm;
"""
open(os.path.join(root, "supabase_v35_meter_direction.sql"), "w").write(sql)
print("wrote supabase_v35_meter_direction.sql")
