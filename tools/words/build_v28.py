#!/usr/bin/env python3
"""Build supabase_v28_word_families.sql from families.py and print a coverage report for Grade 5.
Usage: build_v28.py <g5.json> <feelings.json> <linking.json>   (exports of the sets, {items:[{term, tags}]})"""
import json, sys, os, collections
sys.path.insert(0, os.path.dirname(__file__))
from families import NEW, SCALES, SIM, OPP, THEMES, TYPES

g5 = [x for x in json.load(open(sys.argv[1]))["items"] if x.get("kind", "term") == "term"]
fee = json.load(open(sys.argv[2]))["items"]; link = json.load(open(sys.argv[3]))["items"]
known = {x["term"].lower(): x["term"] for x in g5 + fee + link}
for h in ["Full", "Peckish", "Hungry", "Ravenous", "Famished"]: known[h.lower()] = h
g5set = {x["term"].lower() for x in g5}
existing_tags = {}
for x in g5 + fee: existing_tags.setdefault(x["term"].lower(), []).extend(t for t in (x.get("tags") or []) if t not in existing_tags.get(x["term"].lower(), []))

new = []
for line in NEW.strip().splitlines():
    p = line.split("|"); assert len(p) == 9, line
    h, t, th, emo, syl, pron, mean, ex, tr = p
    assert h.lower() not in known, "already exists: " + h
    assert syl.replace("-", "") == h.lower(), "syllables: " + h
    assert "[" in ex, "example needs [word]: " + h
    base = [TYPES[t]] + ([THEMES[c] for c in th.split(";")] if th != "-" else [])
    new.append(dict(h=h, emoji=emo, syl=syl, pron=pron, mean=mean, ex=ex, tr=tr, base=base))
    known[h.lower()] = h

add = collections.defaultdict(list); errs = []; why = {}
def need(w, ctx):
    if w.lower() not in known: errs.append(f"{ctx}: unknown word {w}"); return None
    return known[w.lower()]
for name, (faces, members) in SCALES.items():
    for w, r in members:
        h = need(w, name)
        if h: add[h].append(f"📶 {name}: {'+' if r > 0 else ''}{r}"); why.setdefault(h, 1)
for g, ws in SIM.items():
    ws = ws.split()
    if len(ws) < 2: errs.append(f"≈ {g}: needs 2+ words"); continue
    for w in ws:
        w = w.replace("_", " "); h = need(w, "≈ " + g)
        if h: add[h].append(f"≈ {g}"); why.setdefault(h, 2)
for g, sides in OPP.items():
    for side, ws in sides.items():
        for w in ws.split():
            h = need(w, "⇄ " + g)
            if h: add[h].append(f"⇄ {g}: {side}"); why.setdefault(h, 3)
if errs: print("\n".join(errs)); sys.exit(1)

# tag limit (16) after merging
for h, tags in add.items():
    base = next((n["base"] for n in new if n["h"] == h), existing_tags.get(h.lower(), []))
    scales = {t.split(":")[0] for t in tags if t.startswith("📶")}
    merged = [t for t in base if not (t.startswith("📶") and t.split(":")[0] in scales)]
    merged = list(dict.fromkeys(merged + tags))
    if len(merged) > 16: errs.append(f"too many tags ({len(merged)}): {h}")
if errs: print("\n".join(errs)); sys.exit(1)

# coverage report
rep = []
for x in g5:
    h = x["term"]; old = existing_tags.get(h.lower(), []); tags = list(dict.fromkeys(old + add.get(h, [])))
    m = [t for t in tags if t.startswith("📶")]; s = [t for t in tags if t.startswith("≈")]; o = [t for t in tags if t.startswith("⇄")]
    rep.append((h, len(m), len(s), len(o)))
print(f"Grade 5: {len(rep)} words · on a meter {sum(1 for r in rep if r[1])} · similar {sum(1 for r in rep if r[2])} · opposite {sum(1 for r in rep if r[3])}")
print("no similar group:", ", ".join(r[0] for r in rep if not r[2]) or "-")
print("no opposite:", ", ".join(r[0] for r in rep if not r[3]) or "-")
print("nothing at all:", ", ".join(r[0] for r in rep if not (r[1] or r[2] or r[3])) or "-")
print(f"new dictionary words: {len(new)} · meters {len(SCALES)} · similar groups {len(SIM)} · opposite groups {len(OPP)}")

q = lambda s: "'" + s.replace("'", "''") + "'"
arr = lambda a: "array[" + ",".join(q(t) for t in a) + "]::text[]"
EXP = "00000000-0000-4000-8000-00000000e5f1"
out = [f"""-- =====================================================================
-- Helper Academy — v28: word families for every Grade 5 word
--   📶 meters ({len(SCALES)} scales: feelings plus size, distance, sound, danger, energy, …)
--   ≈ similar words ({len(SIM)} groups) and ⇄ opposites ({len(OPP)} groups)
-- {len(new)} new words go into the shared dictionary and a new box "Word Explorer: Grade 5 families"
-- (public, a Story builder word box). Tags are ADDED (never removed), except that a word keeps one
-- place per meter. Generated by tools/words/build_v28.py from tools/words/families.py. Safe to re-run.
-- Run AFTER supabase_v27_hunger_scale.sql.
-- =====================================================================
insert into public.study_sets (id, owner_id, author_name, institution_id, subject_id, level_code, title, description,
                               language, translation_lang, units, visibility, story_box)
select '{EXP}', p.id, 'Ab', null, 1, 'any', 'Word Explorer: Grade 5 families',
  'More words around the Grade 5 words: the rest of each meter, similar words and opposites, so you can go beyond one word.',
  'en', 'ar', '[{{"u": 1, "name": "Meter words"}},{{"u": 2, "name": "Similar words"}},{{"u": 3, "name": "Opposite words"}}]'::jsonb, 'public', 'words'
from public.profiles p join auth.users u on u.id = p.id where u.email = 'albarq2000@hotmail.com'
on conflict (id) do update set title = excluded.title, description = excluded.description, units = excluded.units, story_box = excluded.story_box;

-- add tags to a dictionary word (and to any set-specific tag override); one place per meter
create or replace function pg_temp.add_family_tags(p_head text, p_tags text[]) returns int language plpgsql as $$
declare n int;
begin
  update public.words w set tags = (
      select array(select distinct t from unnest(
        array(select t0 from unnest(w.tags) t0 where not (t0 like '📶 %' and split_part(t0, ':', 1) in (select split_part(x, ':', 1) from unnest(p_tags) x where x like '📶 %')))
        || p_tags) t order by t)), updated_at = now()
  where w.lang = 'en' and lower(w.headword) = lower(p_head) and w.sense = '';
  get diagnostics n = row_count;
  update public.set_entries e set tags = (
      select array(select distinct t from unnest(
        array(select t0 from unnest(e.tags) t0 where not (t0 like '📶 %' and split_part(t0, ':', 1) in (select split_part(x, ':', 1) from unnest(p_tags) x where x like '📶 %')))
        || p_tags) t order by t))
  where e.tags is not null and e.word_id in (select id from public.words where lang = 'en' and lower(headword) = lower(p_head) and sense = '');
  return n;
end $$;

-- new dictionary words
insert into public.words (lang, headword, sense, meaning, example, translation, syllables, pronunciation, emoji, tags, owner_id)
select 'en', v.h, '', v.m, v.e, v.t, v.s, v.p, v.j, '{{}}'::text[],
       (select p.id from public.profiles p join auth.users u on u.id = p.id where u.email = 'albarq2000@hotmail.com')
from (values
"""]
out.append(",\n".join(f"  ({q(n['h'])}, {q(n['mean'])}, {q(n['ex'])}, {q(n['tr'])}, {q(n['syl'])}, {q(n['pron'])}, {q(n['emoji'])})" for n in new))
out.append(""") as v(h, m, e, t, s, p, j)
on conflict (lang, lower(headword), sense) do nothing;

-- family tags (new words also get their word type and themes)
select count(*) filter (where n = 0) as words_not_found from (values
""")
rows = []
for h, tags in add.items():
    base = next((n["base"] for n in new if n["h"] == h), [])
    rows.append(f"  (pg_temp.add_family_tags({q(h)}, {arr(base + tags)}))")
out.append(",\n".join(rows))
out.append(""") as r(n);

-- link the new words into the Word Explorer box
insert into public.set_entries (id, set_id, position, kind, unit, also_units, word_id)
select ('00000000-0000-4000-8000-' || lpad(to_hex(x.k), 8, '0') || 'e5f1')::uuid, '""" + EXP + """', x.k, 'term', x.u, '{}', w.id
from (values
""")
out.append(",\n".join(f"  ({k + 1}, {why.get(n['h'], 2)}, {q(n['h'].lower())})" for k, n in enumerate(new)))
out.append(""") as x(k, u, hw)
join public.words w on w.lang = 'en' and lower(w.headword) = x.hw and w.sense = ''
on conflict (id) do nothing;

-- check: Grade 5 coverage as the site sees it
select count(*) as grade5_words,
       count(*) filter (where exists (select 1 from unnest(tags) t where t like '📶 %')) as on_a_meter,
       count(*) filter (where exists (select 1 from unnest(tags) t where t like '≈ %')) as with_similar,
       count(*) filter (where exists (select 1 from unnest(tags) t where t like '⇄ %')) as with_opposite,
       (select count(*) from public.set_items where set_id = '""" + EXP + """') as explorer_words
from public.set_items where set_id = '00000000-0000-4000-8000-000000000005' and kind = 'term';
""")
open(os.path.join(os.path.dirname(__file__), "..", "..", "supabase_v28_word_families.sql"), "w").write("".join(out))
json.dump({k: (v[0] or "") for k, v in SCALES.items()}, open(os.path.join(os.path.dirname(__file__), "faces.json"), "w"), ensure_ascii=False)
