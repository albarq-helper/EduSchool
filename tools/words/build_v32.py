#!/usr/bin/env python3
"""Build supabase_v32_director.sql from director.py."""
import os, sys
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.join(here, "..", "..")
sys.path.insert(0, here)
from director import DIR, DIR_UNITS
q = lambda s: "'" + s.replace("'", "''") + "'"
arr = lambda a: "array[" + ",".join(q(t) for t in a) + "]::text[]"
SET = "00000000-0000-4000-8000-00000000d1ec"
rows = []
for line in DIR.strip().splitlines():
    p = line.split("|"); assert len(p) == 7, line
    u, h, e, m, ex, ar, film = p; u = int(u); assert "[" in ex, h
    tags = ["Music" if u == 6 else "Camera", "Film & music", "🎬 " + DIR_UNITS[u - 1]]
    rows.append((u, h, e, m, ex, ar, film, tags))
v31 = open(os.path.join(root, "supabase_v31_famous_sayings.sql")).read()
fn = v31[v31.index("create or replace function public.save_set_items"):v31.index("grant execute on function public.save_set_items(uuid, jsonb, uuid[]) to authenticated;")]
fn = fn.replace("'literal','literal_tr','equivalent','author'];", "'literal','literal_tr','equivalent','author','film'];").replace("        author = null,\n", "        author = null,\n        film = null,\n")
assert "'film'];" in fn and "film = null" in fn
owner = "(select p.id from public.profiles p join auth.users u on u.id = p.id where u.email = 'albarq2000@hotmail.com')"
units = "'[" + ",".join('{"u": %d, "name": "%s"}' % (k + 1, n) for k, n in enumerate(DIR_UNITS)) + "]'::jsonb"
view = v31[v31.index("create or replace view public.set_items"):v31.index("grant select on public.set_items to anon, authenticated;")]
view = view.replace("       coalesce(e.author, w.author, '') as author\n", "       coalesce(e.author, w.author, '') as author,\n       coalesce(e.film, w.film, '') as film\n")
assert "as film" in view
out = f"""-- =====================================================================
-- Helper Academy — v32: Director's Toolbox and soundtracks
--   * new word field "film": the instruction a word sends to the video AI (camera, light) or the music AI
--   * public set "Director's Toolbox" ({len(rows)}): shot sizes, angles, camera moves, light, transitions, music moods
--     — a Story builder box of kind 'director' (the student puts 🎥 camera and 🎵 music cards into scenes)
--   * table story_music: soundtracks made with ElevenLabs Music by the "music" Edge Function (parent only)
-- Generated by tools/words/build_v32.py from tools/words/director.py. Safe to re-run. Run AFTER v31.
-- =====================================================================
alter table public.words add column if not exists film text not null default '';
alter table public.set_entries add column if not exists film text;

{view}grant select on public.set_items to anon, authenticated;

{fn}grant execute on function public.save_set_items(uuid, jsonb, uuid[]) to authenticated;

alter table public.study_sets drop constraint if exists study_sets_story_box_check;
alter table public.study_sets add constraint study_sets_story_box_check check (story_box is null or story_box in ('link', 'words', 'sayings', 'director'));

insert into public.study_sets (id, owner_id, author_name, institution_id, subject_id, level_code, title, description,
                               language, translation_lang, units, visibility, story_box)
select '{SET}', {owner}, 'Ab', null, 1, 'any', 'Director''s Toolbox',
  'How film directors talk: shot sizes, camera angles and moves, light, transitions and music moods.',
  'en', 'ar', {units}, 'public', 'director'
on conflict (id) do update set title = excluded.title, description = excluded.description, units = excluded.units, story_box = excluded.story_box;

insert into public.words (lang, headword, sense, meaning, example, translation, syllables, pronunciation, emoji, film, tags, owner_id)
select 'en', v.h, '', v.m, v.e, v.t, '', '', v.j, v.f, v.tg, {owner}
from (values
""" + ",\n".join(f"  ({q(h)}, {q(m)}, {q(ex)}, {q(ar)}, {q(e)}, {q(film)}, {arr(tg)})" for u, h, e, m, ex, ar, film, tg in rows) + """
) as v(h, m, e, t, j, f, tg)
on conflict (lang, lower(headword), sense) do update set film = excluded.film;

insert into public.set_entries (id, set_id, position, kind, unit, also_units, word_id)
select x.id::uuid, '""" + SET + """', x.k, 'term', x.u, '{}', w.id
from (values
""" + ",\n".join(f"  ({q(SET[:24] + '0001' + SET[-4:] + format(k + 1, '04x'))}, {k + 1}, {r[0]}, {q(r[1].lower())})" for k, r in enumerate(rows)) + """
) as x(id, k, u, hw)
join public.words w on w.lang = 'en' and lower(w.headword) = x.hw and w.sense = ''
on conflict (id) do nothing;

-- soundtracks: scene 0 = the whole movie, 1..50 = one scene
create table if not exists public.story_music (
  id          uuid primary key default gen_random_uuid(),
  story_id    uuid not null references public.stories(id) on delete cascade,
  scene       int  not null default 0 check (scene between 0 and 50),
  prompt      text not null check (length(prompt) between 3 and 4100),
  style       text not null default '',
  length_ms   int  not null default 30000 check (length_ms between 3000 and 300000),
  audio_url   text not null default '',
  status      text not null default 'ready' check (status in ('ready','failed')),
  error       text not null default '',
  created_by  uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  created_at  timestamptz not null default now()
);
create index if not exists story_music_story on public.story_music (story_id, scene, created_at desc);
alter table public.story_music enable row level security;
drop policy if exists "see music of visible stories" on public.story_music;
create policy "see music of visible stories" on public.story_music for select to authenticated using (public.can_see_story(story_id));
drop policy if exists "director adds music" on public.story_music;
create policy "director adds music" on public.story_music for insert to authenticated with check (created_by = auth.uid() and public.can_direct_story(story_id));
drop policy if exists "director deletes music" on public.story_music;
create policy "director deletes music" on public.story_music for delete to authenticated using (public.can_direct_story(story_id));
grant select, insert, delete on public.story_music to authenticated;

-- check
select (select count(*) from public.set_items where set_id = '""" + SET + """') as toolbox,
       (select count(*) from public.set_items where set_id = '""" + SET + """' and film <> '') as with_film,
       (select count(*) from information_schema.tables where table_name = 'story_music') as music_table;
"""
open(os.path.join(root, "supabase_v32_director.sql"), "w").write(out)
print("toolbox", len(rows))
