#!/usr/bin/env python3
"""Build supabase_v29_phrases_idioms.sql from phrases.py (and the save_set_items function in v26)."""
import os, re, sys
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.join(here, "..", "..")
sys.path.insert(0, here)
from phrases import PV, ID, PV_UNITS, ID_UNITS
from families import THEMES

q = lambda s: "'" + s.replace("'", "''") + "'"
arr = lambda a: "array[" + ",".join(q(t) for t in a) + "]::text[]"
def tags(spec, base):
    out = list(base)
    for t in spec.split(";"):
        t = t.strip()
        if t: out.append(THEMES.get(t, t))
    return list(dict.fromkeys(out))

PVSET, IDSET = "00000000-0000-4000-8000-00000000f4a5", "00000000-0000-4000-8000-00000000d10e"
rows = []  # (set, unit, head, emoji, meaning, example, tr, literal, literal_tr, equivalent, tags)
for line in PV.strip().splitlines():
    p = line.split("|"); assert len(p) == 7, line
    u, h, e, m, ex, tr, tg = p
    assert "[" in ex, h
    rows.append((PVSET, int(u), h, e, m, ex, tr, "", "", "", tags(tg, ["Action"])))
for line in ID.strip().splitlines():
    p = line.split("|"); assert len(p) == 10, line
    u, h, e, m, lit, ex, tr, litar, eq, tg = p
    assert "[" in ex, h
    rows.append((IDSET, int(u), h, e, m, ex, tr, lit, litar, eq, tags(tg, [])))
heads = [r[2].lower() for r in rows]; assert len(heads) == len(set(heads)), "duplicate headword"

v26 = open(os.path.join(root, "supabase_v26_dictionary.sql")).read()
fn = v26[v26.index("create or replace function public.save_set_items"):v26.index("grant execute on function public.save_set_items(uuid, jsonb, uuid[]) to authenticated;")]
fn = fn.replace("'image_url','anim_url','audio_url','video_url','emoji'];", "'image_url','anim_url','audio_url','video_url','emoji',\n                                  'literal','literal_tr','equivalent'];")
fn = fn.replace("        emoji = null,\n        tags = null;", "        emoji = null,\n        literal = null,\n        literal_tr = null,\n        equivalent = null,\n        tags = null;")
assert "'literal','literal_tr','equivalent'" in fn and "equivalent = null" in fn

units = lambda L: "'[" + ",".join('{"u": %d, "name": "%s"}' % (k + 1, n) for k, n in enumerate(L)) + "]'::jsonb"
owner = "(select p.id from public.profiles p join auth.users u on u.id = p.id where u.email = 'albarq2000@hotmail.com')"
out = [f"""-- =====================================================================
-- Helper Academy — v29: Phrasal Verbs and Idioms
--   * three new word fields, used by idioms: literal (word-for-word meaning), literal_tr (that, translated)
--     and equivalent (the saying with the same idea in the translation language, e.g. Arabic)
--     — on the dictionary (words), on set links (set_entries), in the set_items view and in save_set_items
--   * two public sets owned by the parent: Phrasal Verbs ({sum(1 for r in rows if r[0] == PVSET)}) and Idioms ({sum(1 for r in rows if r[0] == IDSET)}),
--     tagged with themes, meters (📶), similar words (≈) and opposites (⇄)
-- Generated by tools/words/build_v29.py from tools/words/phrases.py. Safe to re-run. Run AFTER v28.
-- =====================================================================
alter table public.words add column if not exists literal text not null default '';
alter table public.words add column if not exists literal_tr text not null default '';
alter table public.words add column if not exists equivalent text not null default '';
alter table public.set_entries add column if not exists literal text;
alter table public.set_entries add column if not exists literal_tr text;
alter table public.set_entries add column if not exists equivalent text;

create or replace view public.set_items with (security_invoker = on) as
select e.id, e.set_id, e.position, e.kind, e.unit, e.also_units,
       coalesce(e.term, w.headword) as term,
       coalesce(e.meaning, w.meaning, '') as meaning,
       coalesce(e.example, w.example, '') as example,
       coalesce(e.translation, w.translation, '') as translation,
       coalesce(e.syllables, w.syllables, '') as syllables,
       coalesce(e.image_url, w.image_url, '') as image_url,
       coalesce(e.anim_url, w.anim_url, '') as anim_url,
       coalesce(e.audio_url, w.audio_url, '') as audio_url,
       e.choices, e.answer, e.created_at,
       coalesce(e.pronunciation, w.pronunciation, '') as pronunciation,
       coalesce(e.sound_hint, w.sound_hint, '') as sound_hint,
       coalesce(e.video_url, w.video_url, '') as video_url,
       coalesce(e.emoji, w.emoji, '') as emoji,
       coalesce(e.tags, w.tags, '{{}}') as tags,
       e.word_id, coalesce(w.sense, '') as sense,
       (e.word_id is not null and e.meaning is not null) as set_meaning,
       coalesce(e.literal, w.literal, '') as literal,
       coalesce(e.literal_tr, w.literal_tr, '') as literal_tr,
       coalesce(e.equivalent, w.equivalent, '') as equivalent
from public.set_entries e left join public.words w on w.id = e.word_id;
grant select on public.set_items to anon, authenticated;

-- saving from the editor now keeps the three new fields too
{fn}grant execute on function public.save_set_items(uuid, jsonb, uuid[]) to authenticated;

insert into public.study_sets (id, owner_id, author_name, institution_id, subject_id, level_code, title, description,
                               language, translation_lang, units, visibility, story_box)
select x.id::uuid, {owner}, 'Ab', null, 1, 'any', x.title, x.descr, 'en', 'ar', x.units, 'public', 'words'
from (values
  ('{PVSET}', 'Phrasal Verbs', 'Two- and three-word verbs like wake up, look after and give up, with their meaning in English and Arabic.', {units(PV_UNITS)}),
  ('{IDSET}', 'Idioms', 'English sayings that mean more than their words: the real meaning, the word-for-word meaning, and the Arabic saying with the same idea.', {units(ID_UNITS)})
) as x(id, title, descr, units)
on conflict (id) do update set title = excluded.title, description = excluded.description, units = excluded.units, story_box = excluded.story_box;

insert into public.words (lang, headword, sense, meaning, example, translation, syllables, pronunciation, emoji, literal, literal_tr, equivalent, tags, owner_id)
select 'en', v.h, '', v.m, v.e, v.t, '', '', v.j, v.l, v.lt, v.eq, v.tg, {owner}
from (values
"""]
out.append(",\n".join(f"  ({q(r[2])}, {q(r[4])}, {q(r[5])}, {q(r[6])}, {q(r[3])}, {q(r[7])}, {q(r[8])}, {q(r[9])}, {arr(r[10])})" for r in rows))
out.append(""") as v(h, m, e, t, j, l, lt, eq, tg)
on conflict (lang, lower(headword), sense) do update set literal = excluded.literal, literal_tr = excluded.literal_tr, equivalent = excluded.equivalent,
  tags = (select array(select distinct t from unnest(public.words.tags || excluded.tags) t order by t));

insert into public.set_entries (id, set_id, position, kind, unit, also_units, word_id)
select x.id::uuid, x.s::uuid, x.k, 'term', x.u, '{}', w.id
from (values
""")
# entry ids: same prefix as the set, last 4 hex = position, marked by a leading 1 in the last group
ent = []
for s in (PVSET, IDSET):
    k = 0
    for r in rows:
        if r[0] != s: continue
        k += 1
        eid = s[:24] + "0001" + s[-4:] + f"{k:04x}"
        ent.append(f"  ({q(eid)}, '{s}', {k}, {r[1]}, {q(r[2].lower())})")
out.append(",\n".join(ent))
out.append(""") as x(id, s, k, u, hw)
join public.words w on w.lang = 'en' and lower(w.headword) = x.hw and w.sense = ''
on conflict (id) do nothing;

-- check
select s.title, count(i.*) as items,
       count(*) filter (where i.literal <> '') as with_literal,
       count(*) filter (where i.equivalent <> '') as with_arabic_saying,
       count(*) filter (where i.translation <> '') as with_translation
from public.study_sets s join public.set_items i on i.set_id = s.id
where s.id in ('""" + PVSET + "', '" + IDSET + """') group by s.title order by s.title;
""")
open(os.path.join(root, "supabase_v29_phrases_idioms.sql"), "w").write("".join(out))
print("phrasal verbs", sum(1 for r in rows if r[0] == PVSET), "· idioms", sum(1 for r in rows if r[0] == IDSET))
